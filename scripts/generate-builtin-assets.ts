import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import * as prettier from 'prettier';

const source = resolve(import.meta.dir, '..', 'skills', 'builtin');
const output = resolve(import.meta.dir, '..', 'src', 'skills', 'builtin-assets.generated.ts');

async function collect(directory: string, parent = ''): Promise<Record<string, string>> {
  const assets: Record<string, string> = Object.create(null);
  const entries = await readdir(directory, { withFileTypes: true });
  entries.sort((left, right) => (left.name < right.name ? -1 : left.name > right.name ? 1 : 0));
  for (const entry of entries) {
    const relativePath = parent ? `${parent}/${entry.name}` : entry.name;
    const path = resolve(directory, entry.name);
    if (entry.isSymbolicLink())
      throw new Error(`Built-in assets cannot contain symbolic links: ${relativePath}`);
    if (entry.isDirectory()) {
      Object.assign(assets, await collect(path, relativePath));
    } else if (entry.isFile()) {
      const content = await readFile(path);
      const text = content.toString('utf8');
      if (!Buffer.from(text, 'utf8').equals(content))
        throw new Error(`Built-in assets must be UTF-8 text: ${relativePath}`);
      assets[relativePath] = text;
    } else throw new Error(`Unsupported built-in asset: ${relativePath}`);
  }
  return assets;
}

export function collectBuiltinAssets(): Promise<Record<string, string>> {
  return collect(source);
}

export async function generateBuiltinAssets(): Promise<void> {
  const assets = await collectBuiltinAssets();
  const options = await prettier.resolveConfig(output);
  const generated = await prettier.format(
    `// Generated by scripts/generate-builtin-assets.ts. Do not edit.\nexport const builtinAssets: Record<string, string> = ${JSON.stringify(assets, null, 2)};\n`,
    { ...options, parser: 'typescript' },
  );
  await mkdir(dirname(output), { recursive: true });
  try {
    if ((await readFile(output, 'utf8')) === generated) return;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
  }
  await writeFile(output, generated);
}

if (import.meta.main) await generateBuiltinAssets();
